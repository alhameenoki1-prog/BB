def test_the_failed_recipient_is_read_from_every_layout():
    assert bounced_recipient(EXCHANGE_NEW) == "jane.doe@acme.com"
    assert bounced_recipient(EXCHANGE_OLD) == "jane@acme.com"
    assert bounced_recipient(EXCHANGE_ADMIN_SECTION) == "info@toutsemblealler.ml"
    assert bounced_recipient(EXCHANGE_DISPLAY_NAME) == "dfc@xyz.com"
    assert bounced_recipient(EXCHANGE_DELAYED) == "events@pbconventioncenter.com"
    assert bounced_recipient(EXCHANGE_TENANT, exclude="robert@gocalgaryshuttles.com") == "someone@gmail.com"
    assert bounced_recipient(EXCHANGE_RESTRICTED) == "bob@example.org"
    assert bounced_recipient(DSN) == "nobody@gone.example"
    assert bounced_recipient(GMAIL) == "ghost@nowhere.example"
    assert bounced_recipient("", {"X-Failed-Recipients": "lost@x.example"}) == "lost@x.example"
    # Never the sender's own address.
    assert bounced_recipient("Delivery failed for robert@gocalgaryshuttles.com", exclude="robert@gocalgaryshuttles.com") == ""
    assert bounced_recipient("nothing here") == ""


def test_the_original_message_id_is_quoted_from_the_report():
    assert original_message_ids(EXCHANGE_NEW) == ["<abc123@gocalgaryshuttles.com>"]
    assert original_message_ids(EXCHANGE_RESTRICTED) == ["<def456@gocalgaryshuttles.com>"]
    assert original_message_ids(EXCHANGE_ADMIN_SECTION) == ["<68299529a4b42f1f4fe2a89763f0a8d9@gocalgaryshuttles.com>"]   # folded
    assert original_message_ids(DSN) == []
    assert original_message_ids("Diagnostic-Code: smtp;550 5.6.0 cannot handle content, InternetMessageId <q@x.co>.") == ["<q@x.co>"]


def test_microsofts_blocked_sender_is_a_verdict_on_the_mailbox_not_the_address():
    kind = bounce_kind(EXCHANGE_RESTRICTED)
    assert kind == SENDER_BLOCKED and kind in BLOCK_KINDS and kind in SENDER_BLOCK_KINDS
    reason, hint = bounce_reason(EXCHANGE_RESTRICTED)
    assert "5.1.8" in reason and "Restricted entities" in hint and "Resume sending" in hint
    assert bounce_kind("550 5.7.750 Service unavailable. Client blocked from sending from unregistered domains") == SENDER_BLOCKED
    assert bounce_kind("550 5.7.705 Service unavailable. Access denied, tenant has exceeded threshold") == SENDER_BLOCKED
    # A real missing address is still that.
    assert bounce_kind(EXCHANGE_NEW) == "no such address"
    assert bounce_kind(EXCHANGE_TENANT) == SENDER_BLOCKED
    assert bounce_kind("550 5.7.501 Access denied, spam abuse detected") == SENDER_BLOCKED
    # The mailbox's or tenant's limit for the day, a temporary restriction: slow down, not stop.
    for text in ("550 5.7.233 Your message can't be sent because your tenant has exceeded its daily limit for sending "
                 "email to external recipients (tenant external recipient rate limit).",
                 "550 5.1.90 Your message can't be sent because you've reached your daily limit for message recipients.",
                 "The message can't be submitted because the sender's submission quota was exceeded.",
                 "451 4.7.650 Access denied, please try again later"):
        assert bounce_kind(text) == "sending too fast or too much", text
    # A recipient's own receive limit is neither: the address is fine and we are not blocked.
    assert bounce_kind("550 5.2.122 Recipient's per hour message receive limit exceeded") not in BLOCK_KINDS
    # The report's own sender inside the organisation is Exchange's system address.
    from harvey.integrations.mail_provider import looks_like_bounce
    assert looks_like_bounce("MicrosoftExchange329e71ec88ae4615bbc36ab6ce41109e@gocalgaryshuttles.com", "")
